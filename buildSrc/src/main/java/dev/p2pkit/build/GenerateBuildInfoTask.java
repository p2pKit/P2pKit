package dev.p2pkit.build;

import java.io.File;
import java.util.List;
import org.gradle.api.DefaultTask;
import org.gradle.api.file.DirectoryProperty;
import org.gradle.api.provider.Property;
import org.gradle.api.tasks.CacheableTask;
import org.gradle.api.tasks.Input;
import org.gradle.api.tasks.OutputDirectory;
import org.gradle.api.tasks.TaskAction;

@CacheableTask
public abstract class GenerateBuildInfoTask extends DefaultTask {
    @Input
    public abstract Property<String> getSourceCommit();

    @Input
    public abstract Property<String> getSourceCommitTime();

    @Input
    public abstract Property<Boolean> getRelevantSourceDirty();

    @OutputDirectory
    public abstract DirectoryProperty getOutputDirectory();

    @TaskAction
    public void generate() {
        String commit = getSourceCommit().get();
        String shortCommit = !commit.equals("unknown") && commit.length() >= 7
            ? commit.substring(0, 7)
            : commit;
        String commitTime = getSourceCommitTime().get();
        boolean dirty = getRelevantSourceDirty().get();
        File outputFile = getOutputDirectory().get().getAsFile()
            .toPath()
            .resolve("dev/p2pkit/core/BuildInfo.kt")
            .toFile();
        String content = String.join("\n", List.of(
            "// Generated by :p2p-core:generateBuildInfo. DO NOT EDIT.",
            "@file:Suppress(\"RedundantVisibilityModifier\")",
            "",
            "package dev.p2pkit.core",
            "",
            "/**",
            " * Identity of the p2pkit framework binary the host app is running.",
            " * Generated at build time from `git rev-parse HEAD`. Use [describe]",
            " * for a reproducible single-line log signature.",
            " */",
            "public object BuildInfo {",
            "    public const val COMMIT: String = \"" + commit + "\"",
            "    public const val COMMIT_SHORT: String = \"" + shortCommit + "\"",
            "    public const val DIRTY: Boolean = " + dirty,
            "    public const val COMMIT_TIME: String = \"" + commitTime + "\"",
            "",
            "    @Deprecated(\"Checkout-local branch names are no longer embedded\")",
            "    public const val BRANCH: String = \"not-embedded\"",
            "",
            "    @Deprecated(\"Build time was volatile; use COMMIT_TIME\", ReplaceWith(\"COMMIT_TIME\"))",
            "    public const val BUILD_TIME: String = COMMIT_TIME",
            "",
            "    public fun describe(): String =",
            "        \"p2pkit@\" + COMMIT_SHORT +",
            "            (if (DIRTY) \"-DIRTY\" else \"\") +",
            "            \" (source \" + COMMIT_TIME + \")\"",
            "}",
            ""
        ));
        ProvenanceFiles.writeIfChanged(outputFile, content);
    }
}

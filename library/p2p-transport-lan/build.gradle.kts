kotlin {
    @OptIn(org.jetbrains.kotlin.gradle.dsl.abi.ExperimentalAbiValidation::class)
    abiValidation()

    // Bundles all three iOS arch slices (device arm64 + sim arm64 + sim x64)
    // into a single .xcframework so the Xcode app at samples/iosApp/ can pick the
    // right slice automatically based on SDKROOT. Generated by the Gradle
    // task `assembleP2pKitSharedXCFramework`.
    val xcf = XCFramework("P2pKitShared")

    jvmToolchain(17)
    // Kotlin 2.4 defaults JVM module names to `<group>:<project>`. Preserve
    // the published META-INF/p2p-transport-lan.kotlin_module identity.
    jvm {
        compilerOptions.moduleName.set(project.name)
    }

    android {
        // Android KMP also emits JVM-style module metadata. Keep the rc2 name.
        compilerOptions.moduleName.set(project.name)
        namespace = "dev.p2pkit.transport.lan"
        compileSdk = libs.versions.android.compileSdk.get().toInt()
        minSdk = libs.versions.android.minSdk.get().toInt()
        withHostTest { }
    }

    // iOS LAN/TCP via Bonjour + Network.framework. Same public API as
    // JVM/Android (`transports { lan() }`), backed by NWBrowser / NWListener
    // / NWConnection. Requires iOS 13+; minimum is enforced by the Network
    // framework symbols themselves.
    val iosMinimumVersion = providers.gradleProperty("IOS_MIN_VERSION").get()
    require(iosMinimumVersion.matches(Regex("[0-9]+\\.[0-9]+"))) {
        "IOS_MIN_VERSION must be a major.minor version"
    }
    val iosMinimumVersionOverride =
        "-Xoverride-konan-properties=minVersion.ios=$iosMinimumVersion"
    val iosTargets = listOf(iosX64(), iosArm64(), iosSimulatorArm64())
    iosTargets.forEach { target ->
        // Kotlin 2.4 raises the default iOS floor to 15. Apply the documented
        // Kotlin/Native override to every framework and test binary so the
        // repository's iOS 14 compatibility contract remains explicit.
        target.binaries.configureEach {
            freeCompilerArgs += iosMinimumVersionOverride
        }
        // Wraps NW_PARAMETERS_DISABLE_PROTOCOL / NW_PARAMETERS_DEFAULT_CONFIGURATION
        // in a static-inline C helper so Kotlin never has to box those
        // void-returning block globals as kotlin.Any. See
        // src/nativeInterop/cinterop/p2pkit_nw.h for the rationale.
        target.compilations.getByName("main") {
            cinterops.create("p2pkit_nw") {
                definitionFile.set(
                    project.layout.projectDirectory.file("src/nativeInterop/cinterop/p2pkit_nw.def")
                )
            }
        }
        // Sample-app consumers want a single Swift-importable framework that
        // bundles :p2p-core's types alongside the LAN transport extension.
        // `export(project(":p2p-core"))` lifts the dependency's public API
        // into the framework's Swift surface so consumers can reference
        // P2pKit / AppId / Peer / P2pMessage / ... directly.
        // Run `./gradlew :p2p-transport-lan:linkDebugFrameworkIosSimulatorArm64`
        // (or `linkReleaseFrameworkIosArm64` for device builds) and drop the
        // resulting `.framework` into Xcode — see the maintained sample at samples/iosApp/.
        target.binaries.framework {
            baseName = "P2pKitShared"
            isStatic = false
            export(project(":p2p-core"))
            xcf.add(this)
        }
    }

    sourceSets {
        commonMain.dependencies {
            // `api` rather than `implementation`: the iOS framework's
            // `export(project(":p2p-core"))` above requires the dependency to
            // be in the public API surface. It also matters for JVM/Android
            // consumers — `api` puts p2p-core's public types (P2pKit, Peer,
            // P2pSession, …) on their compile classpath, which the transport's
            // own public `lan()` DSL returns; `implementation` would hide them.
            api(project(":p2p-core"))
            api(libs.kotlinx.coroutines.core)
        }
        commonTest.dependencies {
            implementation(kotlin("test"))
            implementation(libs.kotlinx.coroutines.test)
        }
        jvmMain.dependencies {
            implementation(libs.jmdns)
        }
        // Task #25 (v0.5): Android uses JmDNS instead of NsdManager to own the
        // mDNS cache in-process and unblock per-peer record invalidation that
        // the system NSD daemon does not expose. Pure-Java jar, no native
        // bits, so the same artifact as jvmMain.
        androidMain.dependencies {
            implementation(libs.jmdns)
        }
        getByName("androidHostTest").dependencies {
            implementation(kotlin("test"))
            implementation(libs.kotlinx.coroutines.test)
        }
    }
}

